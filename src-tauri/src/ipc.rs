//! Typed IPC surface: the single registry of commands exposed to the frontend and the
//! generator for `src/shared/ipc/bindings.ts`.
//!
//! Adding a command: implement it in `<module>/commands.rs`, list it in [`builder`],
//! add it to `APP_COMMANDS` in `build.rs`, grant `allow-<command-name>` in
//! `capabilities/default.json`, then run `pnpm bindings`.

use std::path::{Path, PathBuf};

use specta_typescript::Typescript;
use tauri_specta::{collect_commands, collect_events, Builder};

use crate::{
    app_info, collections, connections, databases, documents, dump_profiles, jobs, query_history,
    settings, tools,
};

/// Location of the generated bindings, relative to the crate root.
#[cfg_attr(not(debug_assertions), allow(dead_code))]
const BINDINGS_RELATIVE_PATH: &str = "../src/shared/ipc/bindings.ts";

/// Header prepended to the generated file.
#[cfg_attr(not(debug_assertions), allow(dead_code))]
const BINDINGS_HEADER: &str =
    "// Generated by tauri-specta from src-tauri/src/ipc.rs. Do not edit by hand; run `pnpm bindings`.";

/// Builds the tauri-specta registry of every command the frontend may call.
pub fn builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        // The UI always sends complete objects, so one shape per type is enough.
        .disable_serde_phases()
        .events(collect_events![jobs::JobUpdated, jobs::JobLogged])
        .commands(collect_commands![
            app_info::commands::get_app_info,
            settings::commands::get_settings,
            settings::commands::update_settings,
            connections::commands::list_connections,
            connections::commands::save_connection,
            connections::commands::delete_connection,
            connections::commands::duplicate_connection,
            connections::commands::get_stored_secrets,
            connections::commands::parse_connection_string,
            connections::commands::build_connection_string,
            connections::commands::test_connection,
            connections::commands::open_connection,
            connections::commands::close_connection,
            connections::commands::list_active_connections,
            connections::transfer::commands::export_connections,
            connections::transfer::commands::inspect_connections_file,
            connections::transfer::commands::import_connections,
            databases::commands::list_databases,
            databases::commands::create_database,
            databases::commands::drop_database,
            collections::commands::list_collections,
            collections::commands::collection_stats,
            collections::commands::create_collection,
            collections::commands::create_view,
            collections::commands::drop_collection,
            collections::commands::rename_collection,
            documents::commands::find_documents,
            documents::commands::count_documents,
            documents::commands::sample_fields,
            query_history::commands::list_queries,
            query_history::commands::record_query,
            query_history::commands::save_favorite_query,
            query_history::commands::delete_favorite_query,
            documents::commands::insert_documents,
            documents::commands::replace_document,
            documents::commands::set_document_field,
            documents::commands::delete_document,
            documents::commands::preview_update_many,
            documents::commands::update_many,
            documents::commands::preview_delete_many,
            documents::commands::delete_many,
            tools::commands::get_tools_info,
            jobs::commands::list_jobs,
            jobs::commands::get_job_log,
            jobs::commands::cancel_job,
            jobs::commands::dismiss_job,
            tools::commands::start_dump,
            tools::commands::inspect_dump,
            tools::commands::start_restore,
            tools::commands::start_export,
            dump_profiles::commands::list_dump_profiles,
            dump_profiles::commands::save_dump_profile,
            dump_profiles::commands::delete_dump_profile,
            dump_profiles::commands::run_dump_profile,
        ])
}

/// Absolute path of the generated TypeScript bindings.
#[cfg_attr(not(debug_assertions), allow(dead_code))]
pub fn bindings_path() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join(BINDINGS_RELATIVE_PATH)
}

/// Writes TypeScript bindings for every registered command and type.
/// Only debug runs and `pnpm bindings` call it, hence unused in release builds.
#[cfg_attr(not(debug_assertions), allow(dead_code))]
pub fn export_bindings(builder: &Builder<tauri::Wry>) -> Result<(), specta_typescript::Error> {
    builder.export(
        Typescript::default().header(BINDINGS_HEADER),
        bindings_path(),
    )
}

#[cfg(test)]
mod tests {
    /// Regenerates the bindings; CI fails if the committed file differs afterwards.
    #[test]
    fn export_bindings() {
        super::export_bindings(&super::builder()).unwrap();
    }
}
