import { useMemo, useState, type ReactNode } from "react";

import { ConfirmDialog } from "@/shared/components/ConfirmDialog";

import type { CollectionTarget } from "../../api/keys";
import {
  useDeleteDocument,
  useInsertDocuments,
  useReplaceDocument,
  useSetField,
} from "../../api/mutations";
import { getField } from "../../lib/bson";
import { toCanonicalJson } from "../../lib/canonical";
import { previewText, toShell } from "../../lib/format";
import { documentId, withoutId } from "../../lib/identity";
import type { LoadedDocument } from "../../types";
import { DocumentActionsContext, type DocumentActions } from "./context";
import { DocumentEditorDialog } from "./DocumentEditorDialog";

type EditorRequest =
  | { kind: "insert" }
  | { kind: "edit"; document: LoadedDocument }
  | { kind: "clone"; document: LoadedDocument };

const EMPTY_DOCUMENT = "{\n  \n}";

interface ProviderProps {
  target: CollectionTarget;
  readOnly: boolean;
  projected: boolean;
  children: ReactNode;
}

/** Owns the insert/edit/clone/delete dialogs and offers the actions to the views. */
export function DocumentActionsProvider({ target, readOnly, projected, children }: ProviderProps) {
  const [editor, setEditor] = useState<EditorRequest | null>(null);
  const [deleting, setDeleting] = useState<LoadedDocument | null>(null);
  const insert = useInsertDocuments(target);
  const replace = useReplaceDocument(target);
  const saveField = useSetField(target).mutateAsync;
  const remove = useDeleteDocument(target);

  const actions = useMemo<DocumentActions>(
    () => ({
      readOnly,
      projected,
      insert: () => {
        setEditor({ kind: "insert" });
      },
      edit: (document) => {
        setEditor({ kind: "edit", document });
      },
      clone: (document) => {
        setEditor({ kind: "clone", document });
      },
      remove: (document) => {
        setDeleting(document);
      },
      setField: async (document, path, original, text) => {
        const id = documentId(document);
        if (id === null) throw new Error("This document has no _id.");
        await saveField({ id, path, originalValue: toCanonicalJson(original), value: text });
      },
    }),
    [readOnly, projected, saveField],
  );

  const closeEditor = () => {
    insert.reset();
    replace.reset();
    setEditor(null);
  };

  return (
    <DocumentActionsContext.Provider value={actions}>
      {children}
      {editor?.kind === "edit" && (
        <DocumentEditorDialog
          title="Edit document"
          description="Change fields, types or nesting. The _id cannot be changed."
          submitLabel="Save"
          initialText={toShell(editor.document.value)}
          pending={replace.isPending}
          error={replace.error}
          onClose={closeEditor}
          onSubmit={(text) => {
            const id = documentId(editor.document);
            if (id === null) return;
            replace.mutate(
              { id, original: editor.document.json, text },
              { onSuccess: closeEditor },
            );
          }}
        />
      )}
      {(editor?.kind === "insert" || editor?.kind === "clone") && (
        <DocumentEditorDialog
          title={editor.kind === "insert" ? "Insert documents" : "Clone document"}
          description="One document, or an array of documents. A missing _id is generated by the server."
          submitLabel="Insert"
          initialText={
            editor.kind === "insert" ? EMPTY_DOCUMENT : toShell(withoutId(editor.document.value))
          }
          pending={insert.isPending}
          error={insert.error}
          onClose={closeEditor}
          onSubmit={(text) => {
            insert.mutate(text, { onSuccess: closeEditor });
          }}
        />
      )}
      <ConfirmDialog
        open={deleting !== null}
        onOpenChange={(open) => {
          if (open) return;
          remove.reset();
          setDeleting(null);
        }}
        title="Delete this document?"
        description={`The document with _id ${deleting ? previewText(getField(deleting.value, "_id") ?? { type: "null" }) : ""} is deleted permanently.`}
        confirmLabel="Delete document"
        destructive
        pending={remove.isPending}
        error={remove.error}
        onConfirm={() => {
          const id = deleting && documentId(deleting);
          if (!id) return;
          remove.mutate(id, {
            onSuccess: () => {
              setDeleting(null);
            },
          });
        }}
      />
    </DocumentActionsContext.Provider>
  );
}
